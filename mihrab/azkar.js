const categoryNames = {
  sabah: "أذكار الصباح",
  masaa: "أذكار المساء",
  sleep: "أذكار قبل النوم",
  wake: "أذكار الاستيقاظ"
};

function getCustomAzkar(cat) {
  return JSON.parse(localStorage.getItem(`custom_azkar_${cat}`)) || [];
}

function setCustomAzkar(cat, data) {
  localStorage.setItem(`custom_azkar_${cat}`, JSON.stringify(data));
}

function getCategoryData(cat) {
  const localCustom = getCustomAzkar(cat);
  return [...defaultAzkarData[cat], ...localCustom];
}

function getProgressStorageKey(cat) {
  return `azkar_progress_${cat}`;
}

function getSavedProgress(cat) {
  return JSON.parse(localStorage.getItem(getProgressStorageKey(cat))) || {};
}

function saveProgress(cat, progressObj) {
  localStorage.setItem(getProgressStorageKey(cat), JSON.stringify(progressObj));
}

function switchCategory(cat) {
  currentCategory = cat;
  
  document.querySelectorAll('#azkar-tabs .tab-btn').forEach(btn => btn.classList.remove('active'));
  const activeBtn = Array.from(document.querySelectorAll('#azkar-tabs .tab-btn')).find(b => b.getAttribute('onclick').includes(cat));
  if (activeBtn) activeBtn.classList.add('active');

  const titleEl = document.getElementById('current-category-title');
  if (titleEl) titleEl.textContent = categoryNames[cat];

  renderAzkarList();
}

function renderAzkarList() {
  const container = document.getElementById('azkar-cards-container');
  if (!container) return;

  const defaultsCount = defaultAzkarData[currentCategory].length;
  const list = getCategoryData(currentCategory);
  const progress = getSavedProgress(currentCategory);

  container.innerHTML = '';
  let completedCount = 0;

  list.forEach((item, index) => {
    const remaining = progress[index] !== undefined ? progress[index] : item.count;
    const isDone = remaining <= 0;
    if (isDone) completedCount++;

    const isCustom = index >= defaultsCount;
    const customIndex = index - defaultsCount;

    const card = document.createElement('div');
    card.className = `card border-0 shadow-sm p-4 rounded-4 zekr-card transition-all ${isDone ? 'zekr-completed' : ''}`;
    
    let actionButtonsHtml = `
      <div class="d-flex align-items-center gap-2 align-self-center align-self-sm-start mt-2 mt-sm-0">
        <button type="button" class="btn ${isDone ? 'btn-secondary disabled' : 'btn-brand'} rounded-pill px-4 py-2 d-flex align-items-center gap-2 count-action-btn" onclick="handleZekrClick(${index})">
          <span>${isDone ? 'اكتمل' : 'باقي:'}</span>
          <span class="fw-bold font-monospace fs-5">${isDone ? '✓' : remaining}</span>
        </button>
    `;

    if (isCustom) {
      actionButtonsHtml += `
        <button type="button" class="btn btn-outline-secondary btn-sm rounded-circle p-2" title="تعديل الذكر" onclick="editCustomZekr(${customIndex})">
          <i class="bi bi-pencil"></i>
        </button>
        <button type="button" class="btn btn-outline-danger btn-sm rounded-circle p-2" title="حذف الذكر" onclick="deleteCustomZekr(${customIndex})">
          <i class="bi bi-trash"></i>
        </button>
      `;
    }

    actionButtonsHtml += `</div>`;

    card.innerHTML = `
      <div class="d-flex justify-content-between align-items-start gap-3 flex-column flex-sm-row">
        <div class="flex-grow-1">
          <p class="fs-5 font-amiri mb-2 zekr-text" style="line-height: 2;">${item.text}</p>
          <small class="text-muted d-block mt-1">العدد الأصلي: ${item.count}</small>
        </div>
        ${actionButtonsHtml}
      </div>
    `;

    container.appendChild(card);
  });

  const progressText = document.getElementById('category-progress-text');
  if (progressText) {
    progressText.textContent = `المنجز: ${completedCount} / ${list.length}`;
  }
}

function handleZekrClick(index) {
  const list = getCategoryData(currentCategory);
  const progress = getSavedProgress(currentCategory);
  const max = list[index].count;
  let currentVal = progress[index] !== undefined ? progress[index] : max;

  if (currentVal > 0) {
    currentVal--;
    progress[index] = currentVal;
    saveProgress(currentCategory, progress);

    if (navigator.vibrate) {
      if (currentVal === 0) {
        navigator.vibrate([100, 50, 100]);
      } else {
        navigator.vibrate(35);
      }
    }

    renderAzkarList();
  }
}

function resetCurrentCategoryCounters() {
  if (confirm("هل تريد تصفير عدادات هذا القسم؟")) {
    localStorage.removeItem(getProgressStorageKey(currentCategory));
    renderAzkarList();
  }
}

function saveNewCategoryZekr() {
  const textInput = document.getElementById('modalZekrText');
  const countInput = document.getElementById('modalZekrCount');

  const text = textInput.value.trim();
  const count = normalizeNumber(countInput.value);

  if (!text) {
    alert("يرجى كتابة نص الذكر أولاً.");
    return;
  }

  const localCustom = getCustomAzkar(currentCategory);
  localCustom.push({ text, count });
  setCustomAzkar(currentCategory, localCustom);

  textInput.value = '';
  countInput.value = '1';

  const modalEl = document.getElementById('addZekrModal');
  const modalInstance = bootstrap.Modal.getInstance(modalEl);
  if (modalInstance) modalInstance.hide();

  renderAzkarList();
}

function editCustomZekr(customIndex) {
  const localCustom = getCustomAzkar(currentCategory);
  const item = localCustom[customIndex];
  if (!item) return;

  const newText = prompt("قم بتعديل نص الذكر:", item.text);
  if (newText === null) return;
  const trimmed = newText.trim();
  if (!trimmed) {
    alert("لا يمكن ترك نص الذكر فارغاً.");
    return;
  }

  const newCountStr = prompt("قم بتعديل عدد التكرار:", item.count);
  if (newCountStr === null) return;
  const newCount = normalizeNumber(newCountStr);

  localCustom[customIndex] = { text: trimmed, count: newCount };
  setCustomAzkar(currentCategory, localCustom);

  const defaultsCount = defaultAzkarData[currentCategory].length;
  const actualIndex = defaultsCount + customIndex;
  const progress = getSavedProgress(currentCategory);
  delete progress[actualIndex];
  saveProgress(currentCategory, progress);

  renderAzkarList();
}

function deleteCustomZekr(customIndex) {
  const localCustom = getCustomAzkar(currentCategory);
  const item = localCustom[customIndex];
  if (!item) return;

  if (confirm(`هل أنت متأكد من حذف الذكر: "${item.text.slice(0, 30)}..."؟`)) {
    localCustom.splice(customIndex, 1);
    setCustomAzkar(currentCategory, localCustom);

    localStorage.removeItem(getProgressStorageKey(currentCategory));
    renderAzkarList();
  }
}

