function normalizeNumber(input) {
  if (!input) return 1;
  const easternNumbers = ['٠','١','٢','٣','٤','٥','٦','٧','٨','٩'];
  let str = input.toString();
  for (let i = 0; i < 10; i++) {
    str = str.replaceAll(easternNumbers[i], i);
  }
  const parsed = parseInt(str.trim(), 10);
  return isNaN(parsed) || parsed <= 0 ? 1 : parsed;
}

